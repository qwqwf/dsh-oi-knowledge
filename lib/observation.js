const OBS_INDEX = new Map()

export function obsIndex() {
  return OBS_INDEX
}

export function obsDepth(path) {
  return path.split('/').length - 1
}

/** 按文本匹配观察树叶子节点（名字或别名出现在文本里）。 */
export function matchObsNodes(text) {
  const source = String(text || '')
  if (!source) return []
  const hits = []
  for (const [path, spec] of OBS_TAXONOMY) {
    if (path === OBS_ROOT) continue
    const names = [path.split('/').pop(), ...(spec.aliases || [])]
    for (const name of names) {
      if (!name || name.length < 2) continue
      if (source.includes(name)) {
        hits.push(path)
        break
      }
    }
  }
  return hits
}

/** 观察句式总数，用于统计和面板展示。 */
export function obsPatternCount() {
  return OBS_TAXONOMY.reduce((sum, [, spec]) => sum + (spec.patterns || []).length, 0)
}
